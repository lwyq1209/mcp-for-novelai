import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile, rm, access } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const check = process.argv.includes('--check');
const contracts = path.join(root, 'contracts');
const built = path.join(contracts, '.build');
const contractNames = ['library-contracts'];
const sources = [...contractNames.map(name => `contracts/src/${name}.mts`), 'contracts/tsconfig.json', 'scripts/build-contracts.mjs'];
const hash = createHash('sha256');
for (const name of sources) hash.update(name).update('\0').update(await readFile(path.join(root, name))).update('\0');
const sourceSha256 = hash.digest('hex');

try {
  const result = spawnSync(process.execPath, [path.join(root, 'node_modules/typescript/bin/tsc'), '-p', path.join(contracts, 'tsconfig.json')], { cwd: root, encoding: 'utf8' });
  if (result.status !== 0) throw new Error(`Contract declaration build failed:\n${result.stdout}${result.stderr}`);
  const destinations = [path.join(contracts, 'generated')];
  if (await access(path.join(root, 'client/src')).then(() => true, () => false)) destinations.push(path.join(root, 'client/src/generated'));
  for (const contractName of contractNames) {
    const { schemas } = await import(pathToFileURL(path.join(built, `${contractName}.mjs`)).href);
    const json = `${JSON.stringify({ schemaVersion: 1, sourceSha256, schemas }, null, 2)}\n`;
    const declaration = `// Generated by build-contracts.mjs; source SHA-256: ${sourceSha256}\n${await readFile(path.join(built, `${contractName}.d.mts`), 'utf8')}`;
    for (const directory of destinations) {
      if (!check) await mkdir(directory, { recursive: true });
      for (const [name, content] of [[`${contractName}.json`, json], [`${contractName}.d.mts`, declaration]]) {
        const file = path.join(directory, name);
        if (check) {
          if (await readFile(file, 'utf8').catch(() => '') !== content) throw new Error(`Stale contract artifact: ${path.relative(root, file)}. Run npm run build:contracts.`);
        } else await writeFile(file, content);
      }
    }
  }
  console.log(`Contract ${check ? 'check' : 'build'} passed (${contractNames.length} contracts, ${destinations.length} destinations, ${sourceSha256.slice(0, 12)}).`);
} finally {
  await rm(built, { recursive: true, force: true });
}
